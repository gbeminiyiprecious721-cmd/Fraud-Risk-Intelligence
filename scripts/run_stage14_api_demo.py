"""Stage 14 -- real local Uvicorn demonstration.

Starts the actual `src.api:app` as a real, separate Uvicorn process
bound to 127.0.0.1 only (never 0.0.0.0, never a public interface), no
`--reload`, a single worker. Makes REAL HTTP requests against it over
localhost, measures actual observed latency, and stops the server
afterward. Never claims this local measurement represents production
throughput or any latency SLA -- Stage 1 never defined one.

TRAIN-ONLY in effect: the served artifact was built from `train` only
(Stage 13); this script never touches `final_test` or any dataset file
itself.
"""

from __future__ import annotations

import json
import platform
import socket
import subprocess
import sys
import time
from pathlib import Path

import httpx

ROOT = Path(__file__).resolve().parent.parent
PYTHON = ROOT / ".venv" / "bin" / "python3"
DOCS_DIR = ROOT / "docs"

N_WARM_REQUESTS = 50


def section(title: str) -> None:
    print(f"\n{'=' * 10} {title} {'=' * 10}", flush=True)


def find_free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def wait_for_health(base_url: str, timeout_seconds: float = 20.0) -> float:
    t0 = time.perf_counter()
    deadline = t0 + timeout_seconds
    while time.perf_counter() < deadline:
        try:
            resp = httpx.get(f"{base_url}/health", timeout=1.0)
            if resp.status_code == 200 and resp.json().get("artifact_loaded"):
                return time.perf_counter() - t0
        except httpx.HTTPError:
            pass
        time.sleep(0.05)
    raise RuntimeError("Server did not become healthy within the timeout.")


def main() -> dict:
    report: dict = {}
    port = find_free_port()
    base_url = f"http://127.0.0.1:{port}"

    section("0. Start the real Uvicorn process (127.0.0.1 only, no reload, 1 worker)")
    proc = subprocess.Popen(
        [str(PYTHON), "-m", "uvicorn", "src.api:app", "--host", "127.0.0.1", "--port", str(port), "--workers", "1"],
        cwd=str(ROOT), stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
    )
    try:
        startup_seconds = wait_for_health(base_url)
        print(f"Server healthy after {startup_seconds:.3f}s (process startup + artifact load, bound to 127.0.0.1:{port})")
        report["startup_seconds_including_artifact_load"] = round(startup_seconds, 3)

        section("1. GET /health")
        health = httpx.get(f"{base_url}/health", timeout=5.0)
        print(health.status_code, health.json())
        report["health"] = {"status_code": health.status_code, "body": health.json()}
        assert health.status_code == 200 and health.json()["artifact_loaded"] is True

        section("2. GET /version")
        version = httpx.get(f"{base_url}/version", timeout=5.0)
        print(version.status_code, version.json())
        report["version"] = {"status_code": version.status_code, "body": version.json()}
        assert version.status_code == 200

        section("3. POST /v1/predict -- a valid synthetic transaction")
        schema_raw_columns = None
        # Build a valid payload from the REAL artifact's schema (read-only, no fit).
        sys.path.insert(0, str(ROOT))
        from src.production_pipeline import load_artifact
        from src.api import DEFAULT_ARTIFACT_PATH

        artifact, _ = load_artifact(DEFAULT_ARTIFACT_PATH)
        valid_payload = {}
        for col in artifact.schema.raw_columns:
            if col in artifact.schema.numeric_columns:
                valid_payload[col] = 100.0
            elif col == "ProductCD":
                valid_payload[col] = "W"
            elif col == "card4":
                valid_payload[col] = "visa"
            elif col == "card6":
                valid_payload[col] = "debit"
            else:
                valid_payload[col] = "unknown"
        valid_payload["TransactionAmt"] = 125.0

        predict_resp = httpx.post(f"{base_url}/v1/predict", json=valid_payload, timeout=5.0)
        print(predict_resp.status_code, predict_resp.json())
        report["predict_valid"] = {"status_code": predict_resp.status_code, "body": predict_resp.json()}
        assert predict_resp.status_code == 200

        section("4. POST /v1/predict -- a controlled 4xx for an invalid transaction (missing field)")
        invalid_payload = dict(valid_payload)
        del invalid_payload["TransactionAmt"]
        invalid_resp = httpx.post(f"{base_url}/v1/predict", json=invalid_payload, timeout=5.0)
        print(invalid_resp.status_code, invalid_resp.json())
        report["predict_invalid"] = {"status_code": invalid_resp.status_code, "body": invalid_resp.json()}
        assert invalid_resp.status_code == 422

        section("5. GET /openapi.json -- autogenerated OpenAPI documentation")
        openapi_resp = httpx.get(f"{base_url}/openapi.json", timeout=5.0)
        paths = sorted(openapi_resp.json().get("paths", {}).keys())
        print(f"status={openapi_resp.status_code} paths={paths}")
        report["openapi"] = {"status_code": openapi_resp.status_code, "paths": paths}
        assert openapi_resp.status_code == 200 and "/v1/predict" in paths

        section(f"6. Latency measurement -- {N_WARM_REQUESTS} warm requests (server already started; this is NOT a throughput/SLA claim)")
        latencies = []
        for _ in range(N_WARM_REQUESTS):
            t0 = time.perf_counter()
            r = httpx.post(f"{base_url}/v1/predict", json=valid_payload, timeout=5.0)
            latencies.append(time.perf_counter() - t0)
            assert r.status_code == 200
        latencies.sort()
        n = len(latencies)
        stats = {
            "n_requests": n,
            "min_seconds": round(latencies[0], 5),
            "median_seconds": round(latencies[n // 2], 5),
            "p95_seconds": round(latencies[int(n * 0.95)], 5),
            "max_seconds": round(latencies[-1], 5),
        }
        print(stats)
        report["warm_request_latency"] = stats
        report["environment"] = {"python_version": platform.python_version(), "platform": platform.platform()}

    finally:
        section("7. Stop the local demonstration server")
        proc.terminate()
        try:
            proc.wait(timeout=10)
        except subprocess.TimeoutExpired:
            proc.kill()
        print("Server stopped.")

    out_path = DOCS_DIR / "_stage14_api_demo_raw.json"
    with open(out_path, "w") as f:
        json.dump(report, f, indent=2, default=str)
    print(f"\nFull structured report written to {out_path}")
    return report


if __name__ == "__main__":
    main()
